#!/usr/bin/env node
// bin/block-defaults-pot.mjs — make `wp i18n make-pot` see the visible text in block.json defaults.
//
// make-pot extracts a block's title/description/keywords but NOT attribute defaults. This writes a
// PHP file that is NEVER loaded — one literal __() per default string — so make-pot picks them up
// (references/i18n.md → "Block attribute defaults"). Run it before `bin/translate`.
//
//   node bin/block-defaults-pot.mjs [blocks-dir] [output-file]
//   defaults: wp-content/themes/<the only theme>/resources/blocks  →  …/resources/lang/block-defaults.php
//
// Skipped on purpose (they are not copy): empty strings, defaults of attributes with an `enum`, and
// slug-like values (no space, no capital letter: `left`, `dark`). Visible one-word copy therefore
// starts with a capital ("Services"), or lives in a default variation instead.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
let [blocksDir, out] = process.argv.slice(2);
if (!blocksDir) {
    const themes = readdirSync(join(root, 'wp-content/themes'), { withFileTypes: true })
        .filter((d) => d.isDirectory() && existsSync(join(root, 'wp-content/themes', d.name, 'resources/blocks')));
    if (themes.length !== 1) {
        console.error('block-defaults-pot: pass the blocks directory (found ' + themes.length + ' candidate themes)');
        process.exit(1);
    }
    blocksDir = join(root, 'wp-content/themes', themes[0].name, 'resources/blocks');
    out ??= join(root, 'wp-content/themes', themes[0].name, 'resources/lang/block-defaults.php');
}
out ??= join(blocksDir, '../lang/block-defaults.php');

const isCopy = (s) => s.trim() !== '' && /[\s\p{Lu}]/u.test(s);

function collect(value, found) {
    if (typeof value === 'string') { if (isCopy(value)) found.add(value); }
    else if (Array.isArray(value)) value.forEach((v) => collect(v, found));
    else if (value && typeof value === 'object') Object.values(value).forEach((v) => collect(v, found));
}

const entries = new Map(); // "domain\0string" -> block names
for (const dir of readdirSync(blocksDir, { withFileTypes: true })) {
    const file = join(blocksDir, dir.name, 'block.json');
    if (!dir.isDirectory() || !existsSync(file)) continue;
    const block = JSON.parse(readFileSync(file, 'utf8'));
    const domain = block.textdomain;
    if (!domain) { console.error(`block-defaults-pot: ${file} has no textdomain`); process.exit(1); }
    for (const attr of Object.values(block.attributes ?? {})) {
        if (!('default' in attr) || attr.enum) continue;
        const found = new Set();
        collect(attr.default, found);
        for (const s of found) {
            const key = `${domain}\0${s}`;
            entries.set(key, [...(entries.get(key) ?? []), block.name]);
        }
    }
}

const php = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const body = [...entries]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, blocks]) => {
        const [domain, s] = key.split('\0');
        return `/* translators: default of ${[...new Set(blocks)].join(', ')} */\n__(${php(s)}, ${php(domain)});`;
    })
    .join('\n');

writeFileSync(out, `<?php\n// Generated by bin/block-defaults-pot.mjs — do not edit, do not load.\n// Exists only so \`wp i18n make-pot\` extracts the block.json attribute defaults.\n${body}\n`);
console.log(`block-defaults-pot: ${entries.size} strings → ${out}`);
